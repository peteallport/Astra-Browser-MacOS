test("injected AI adapter uses native Responses binding with exact Astra and low effort schema", async () => {
  let sent: Record<string, unknown> = {};
  const signal = new AbortController().signal;
  const model = createAstraModelTransport({ gateway(id) {
    assert.equal(id, "fixture");
    return { async run(request, options) {
      assert.equal(request.provider, "openai");
      assert.equal(request.endpoint, "responses");
      assert.deepEqual(request.headers, { "Content-Type": "application/json" });
      assert.deepEqual(options?.extraHeaders, { "cf-aig-byok-alias": "fixture-alias" });
      assert.deepEqual(options?.gateway, { skipCache: true, retries: { maxAttempts: 1 } });
      assert.equal(options?.signal, signal);
      sent = request.query;
      return Response.json({ model: "gpt-6-astra", status: "completed", output_text: JSON.stringify({ fixture: true }) });
    } };
  } }, { gatewayID: "fixture", byokAlias: "fixture-alias", gate: createCloudAccessGate(true) });
  const result = await model.generate({ instructions: "fixture", input: "fixture", schema: {}, maxOutputTokens: 20, signal });
  assert.deepEqual(result.value, { fixture: true });
  assert.equal(sent.model, "gpt-6-astra");
  assert.deepEqual(sent.reasoning, { effort: "low" });
  assert.deepEqual(sent.text, { format: { type: "json_schema", name: "astrabrowse_output", strict: true, schema: {} } });
  assert.equal(sent.store, false);
  const wrong = createAstraModelTransport({ gateway() { return { async run() { return { model: "gpt-other", output_text: "{}" }; } }; } }, { gatewayID: "fixture", gate: createCloudAccessGate(true) });
  await assert.rejects(wrong.generate({ instructions: "", input: "", schema: {}, maxOutputTokens: 1, signal: new AbortController().signal }), { code: "MODEL_MISMATCH" });
});

test("cancellation and an expired total deadline stop compilation", async () => {
  const controller = new AbortController();
  const pipeline = createTranslationPipeline({ captureTransport: { async capture() { return new Promise(() => {}); } }, modelTransport: { async generate() { throw new Error("must not run"); } } });
  const pending = pipeline.capture(evidence().sourceURL, { signal: controller.signal });
  controller.abort();
  await assert.rejects(pending);
  await assert.rejects(pipeline.compile({ ...evidence(), deadlineAt: Date.now() - 1 }), { code: "DEADLINE_EXCEEDED" });
});

