test("upstream errors expose safe diagnostic codes but never raw provider messages", async () => {
  const model = createAstraModelTransport({ gateway() { return { async run() { return Response.json({ error: { code: "invalid_json_schema", param: "text.format.schema", message: "SENSITIVE_FIXTURE_DO_NOT_EXPOSE" } }, { status: 400 }); } }; } }, { gatewayID: "fixture", gate: createCloudAccessGate(true) });
  await assert.rejects(model.generate({ instructions: "", input: "", schema: {}, maxOutputTokens: 1, signal: new AbortController().signal }), error => {
    assert.ok(error instanceof Error);
    assert.match(error.message, /invalid_json_schema/);
    assert.match(error.message, /text\.format\.schema/);
    assert.ok(!error.message.includes("SENSITIVE_FIXTURE_DO_NOT_EXPOSE"));
    return true;
  });
});
