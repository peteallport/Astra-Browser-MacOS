test("injected browser adapter closes its session and skips exploration during revalidation", async () => {
  let closes = 0; let explores = 0; let currentURL = evidence().sourceURL;
  const progress: string[] = [];
  const page = {
    async setViewport() {}, async setBypassServiceWorker() {}, async setRequestInterception() {}, on() {}, async evaluateOnNewDocument() {}, async waitForFunction() {},
    async goto(url: string) { currentURL = url; return { ok: () => true }; }, url: () => currentURL,
    async content() { return fixtureHTML(); }, async createCDPSession() { return { async send() { return { devtoolsFrontendUrl: "https://viewer.example.com/fixture-only" }; } }; },
  };
  const browser = { async close() { closes++; }, async createBrowserContext() { return { async newPage() { return page; } }; } } as unknown as Browser;
  const transport = createBrowserCaptureTransport({ fetch: async () => { throw new Error("No remote requests permitted in fixture test"); } }, {
    gate: createCloudAccessGate(true), resolveDNS: async () => ["8.8.8.8"], launchBrowser: async () => browser,
    explore: async () => { explores++; return []; },
  });
  const captured = await transport.capture(new URL(currentURL), { purpose: "revalidate", deadlineAt: Date.now() + 90_000, onProgress(event) { if (event.type === "status") progress.push(event.stage); } });
  assert.equal(explores, 0);
  assert.equal(closes, 1);
  assert.equal(progress.at(-1), "captured");
  assert.deepEqual(captured.captureProfile, { id: "public-desktop-v1", viewport: { width: 1280, height: 900 } });
});

